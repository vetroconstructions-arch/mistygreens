def generate():
    for page in PAGES:
        slug = page["slug"]
        dir_path = os.path.join(slug)
        os.makedirs(dir_path, exist_ok=True)
        file_path = os.path.join(dir_path, "index.html")

        sections_html = []
        for sec in page["sections"]:
            s_html = f'<section class="article-section"><h2>{sec["title"]}</h2>{sec["content"]}'
            if "table" in sec:
                tbl = sec["table"]
                s_html += '<div class="data-table-wrap"><table><thead><tr>'
                for h in tbl["headers"]:
                    s_html += f'<th>{h}</th>'
                s_html += '</tr></thead><tbody>'
                for row in tbl["rows"]:
                    s_html += '<tr>'
                    for c in row:
                        s_html += f'<td>{c}</td>'
                    s_html += '</tr>'
                s_html += '</tbody></table></div>'
            s_html += '</section>'
            sections_html.append(s_html)

        faqs_html = []
        faq_json_items = []
        for q, a in page["faqs"]:
            faqs_html.append(f'<div class="faq-item"><div class="faq-q">Q: {q}</div><div class="faq-a">{a}</div></div>')
            q_clean = q.replace('"', '\\"')
            a_clean = a.replace('"', '\\"')
            faq_json_items.append(f'{{"@type": "Question", "name": "{q_clean}", "acceptedAnswer": {{"@type": "Answer", "text": "{a_clean}"}}}}')

        full_html = HTML_TEMPLATE.format(
            title=page["title"],
            h1=page["h1"],
            meta_desc=page["meta_desc"],
            keywords=page["keywords"],
            slug=slug,
            category=page["category"],
            intro=page["intro"],
            sections_html="\n".join(sections_html),
            faqs_html="\n".join(faqs_html),
            faq_json=",\n        ".join(faq_json_items)
        )

        with open(file_path, "w", encoding="utf-8") as fp:
            fp.write(full_html)
        print(f"Generated: {file_path}")

if __name__ == "__main__":
    generate()
